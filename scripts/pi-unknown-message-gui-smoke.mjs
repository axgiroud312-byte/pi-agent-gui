// #3/P04: fixed Pi JSONL with future content must remain visible and safe in native GUI.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SessionManager } from '@earendil-works/pi-coding-agent';
import { fixture } from './native-smoke/fixture.mjs';
import { assertCleanExit, closeOwned } from './native-smoke/cleanup.mjs';
import { startPiModel } from './native-smoke/pi-model.mjs';
import { configurePiProfile, isolatePiPackage, verifyPiPackageCleanup } from './native-smoke/pi-package.mjs';

const f = await fixture();
const privateMarker = `DO_NOT_RENDER_${Date.now()}`;
const imageData = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
const report = { at: new Date().toISOString(), pageErrors: [], phases: [],
  boundary: 'Native Electron GUI → Host → pinned Pi 0.87.0 JSONL; future shapes are a fixture appended by the pinned Pi SessionManager, not generated by the model' };
const model = await startPiModel();
let app;

async function showHistory(phase, sessionId) {
  const logs = [];
  app = await f.playwright._electron.launch({ executablePath: f.electronPath,
    args: [fileURLToPath(new URL('./native-smoke/bootstrap.cjs', import.meta.url)), '--lang=zh-CN'],
    cwd: f.root, env: f.env, timeout: 60_000 });
  app.process().stdout?.on('data', chunk => logs.push(String(chunk)));
  app.process().stderr?.on('data', chunk => logs.push(String(chunk)));
  const page = await app.firstWindow();
  page.setDefaultTimeout(20_000);
  page.on('pageerror', error => report.pageErrors.push(error.stack || error.message));
  await page.waitForTimeout(6000);
  for (const name of [/^(使用 API key|Use API key)$/, /^(暂时跳过|Skip for now)$/, /^(退出引导|Exit onboarding)$/]) {
    const button = page.getByRole('button', { name, exact: true });
    if (await button.isVisible()) { await button.click(); await page.waitForTimeout(1200); }
  }
  const addProject = page.getByRole('button', { name: '添加项目', exact: true });
  if (await addProject.isVisible()) {
    await addProject.click();
    await page.getByRole('menuitem', { name: '打开文件夹', exact: true }).click();
  }
  await page.getByTestId('composer-workspace-trigger').filter({ hasText: 'parity-workspace' }).waitFor();
  const item = page.locator(`[data-testid="task-item-${sessionId}"]`);
  await item.waitFor({ timeout: 30_000 });
  await item.click();
  await page.getByText('FUTURE_USER_TEXT', { exact: true }).waitFor({ timeout: 30_000 });
  await page.getByText('FUTURE_ASSISTANT_TEXT', { exact: true }).waitFor({ timeout: 30_000 });
  const types = ['pi.unknown-user-content', 'pi.unknown-assistant-content', 'pi.unknown-message'];
  const phaseReport = { phase, rows: {}, imageVisible: false };
  report.phases.push(phaseReport);
  for (const type of types) {
    const row = page.locator(`[data-pi-extension-message="${type}"]`).first();
    await row.waitFor({ timeout: 30_000 });
    phaseReport.rows[type] = { visible: await row.isVisible(), collapsed: !(await row.evaluate(el => el.open)) };
    assert(phaseReport.rows[type].visible && phaseReport.rows[type].collapsed, `${type} must render folded`);
    await row.locator('summary').click();
    const preview = (await row.textContent()) ?? '';
    phaseReport.rows[type].previewLength = preview.length;
    phaseReport.rows[type].safePreview = preview;
    phaseReport.rows[type].structureVisible = /type|\[field \d+\]|content|role/u.test(preview);
    assert(phaseReport.rows[type].structureVisible, `${type} must show structural information`);
    assert(preview.length < 1200, `${type} preview must be bounded`);
    assert(!preview.includes(privateMarker) && !preview.includes(imageData), `${type} must not reveal private values`);
  }
  const body = (await page.locator('body').textContent()) ?? '';
  assert(!body.includes(privateMarker) && !body.includes(imageData), 'renderer text must not expose private values');
  phaseReport.imageVisible = await page.locator('[data-pi-image]').count() > 0 || await page.locator('img').count() > 0;
  assert(!await page.locator('[data-pi-extension-message="pi.unknown-message"]').filter({ hasText: 'system' }).count(),
    'fixed Pi internal system prompt must not render as an unknown message');
  await page.screenshot({ path: join(f.output, `pi-unknown-message-${phase}.png`) });
  phaseReport.cleanup = await closeOwned(app, f);
  app = undefined;
  assertCleanExit(phaseReport.cleanup, logs, `#3/P04 unknown message ${phase}`);
}

try {
  await isolatePiPackage(f);
  await configurePiProfile(f, { url: model.url, modelId: 'pi-native-test', apiKey: 'fixture-not-a-secret' });
  f.env.PI_CODING_AGENT_SESSION_DIR = join(f.sandbox, 'future-sessions');
  await mkdir(f.env.PI_CODING_AGENT_SESSION_DIR);
  const cli = SessionManager.create(f.workspace, f.env.PI_CODING_AGENT_SESSION_DIR);
  cli.appendMessage({ role: 'user', timestamp: Date.now(), content: [
    { type: 'text', text: 'FUTURE_USER_TEXT' },
    { type: 'image', mimeType: 'image/png', data: imageData },
    { type: 'futureInput', futureField: { secret: privateMarker, count: 2 } },
  ] });
  cli.appendMessage({ role: 'assistant', timestamp: Date.now(), content: [
    { type: 'text', text: 'FUTURE_ASSISTANT_TEXT' },
    { type: 'futureAssistant', futureField: { secret: privateMarker, enabled: true } },
  ], api: 'openai-completions', provider: 'new-provider', model: 'pi-native-test',
  usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0,
    cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } },
  stopReason: 'stop' });
  cli.appendMessage({ role: 'futureRole', timestamp: Date.now(), content: [
    { type: 'futurePayload', futureField: { secret: privateMarker } },
  ] });
  cli.appendSessionInfo('Future Pi message structure');
  const sessionId = cli.getSessionId();
  const sessionFile = cli.getSessionFile();
  assert(sessionFile);
  const before = await readFile(sessionFile, 'utf8');
  assert(before.includes(privateMarker), 'Pi JSONL fixture must retain the complete private payload');
  report.sessionId = sessionId;
  report.fixedPiRoles = cli.getEntries().filter(entry => entry.type === 'message').map(entry => entry.message.role);
  report.fixedPiContentShapes = cli.getEntries().filter(entry => entry.type === 'message').map(entry => ({
    role: entry.message.role,
    parts: Array.isArray(entry.message.content) ? entry.message.content.map(part => ({
      keys: Object.keys(part), valueTypes: Object.fromEntries(Object.entries(part).map(([key, value]) =>
        [key, Array.isArray(value) ? 'array' : value === null ? 'null' : typeof value])),
    })) : [],
  }));
  await showHistory('first-open', sessionId);
  await showHistory('cold-restart', sessionId);
  assert((await readFile(sessionFile, 'utf8')).startsWith(before), 'cold restore must retain original Pi JSONL bytes');
  report.modelRequests = model.requests.length;
  assert.equal(report.modelRequests, 0, 'viewing future message history must not invoke the model');
  await verifyPiPackageCleanup(f);
  report.piPrivatePackageCleanupVerified = true;
  assert.deepEqual(report.pageErrors, []);
  report.ok = true;
} catch (error) {
  report.ok = false;
  report.error = error instanceof Error ? error.stack : String(error);
  throw error;
} finally {
  if (app) report.cleanupAfterFailure = await closeOwned(app, f).catch(error => ({ error: String(error) }));
  await model.close();
  await writeFile(join(f.output, 'pi-unknown-message-gui-report.json'), JSON.stringify(report, null, 2));
}
