import assert from 'node:assert/strict';
import { join } from 'node:path';
import { drag } from './panels.mjs';

// Read-only reference probe. Run only against the independently verified original.
export async function originalInteractions({ app, page, input, model, f, report }) {
  assert.equal(f.baseline, 'original');
  const send = async text => {
    await input.click(); await page.keyboard.type(text);
    await page.getByTestId('v4-composer-send').filter({ visible: true }).first().click();
    await page.getByRole('button', { name: '停止生成', exact: true }).waitFor({ state: 'hidden', timeout: 30_000 });
  };
  await send('PARITY_READ: read README for original tool reference');
  await page.getByText('PARITY_READ_COMPLETE', { exact: true }).waitFor();
  const readTurn = page.locator('section[data-turn-id]').filter({ hasText: 'PARITY_READ: read README' }).first();
  const card = readTurn.locator('[data-testid^="chat-tool-call-block"]').first();
  if (!await card.isVisible()) await readTurn.locator('[data-testid^="chat-assistant-history-trigger"]').first().click();
  await card.waitFor();
  assert.equal(await card.getAttribute('data-status'), 'completed');
  report.actualReadResult = model.requests.some(r => r.toolResults?.some(t => t.content?.includes('NATIVE_PARITY_PREVIEW')));
  assert(report.actualReadResult);
  await page.screenshot({ path: join(f.output, 'original-native-read-current.png') });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.isVisible())?.setContentSize(1920, 1080));
  await page.setViewportSize({ width: 1920, height: 1080 });
  await card.getByRole('button', { name: 'README.md', exact: true }).click();
  await page.getByText('Preview marker: NATIVE_PARITY_PREVIEW', { exact: true }).waitFor();
  await page.screenshot({ path: join(f.output, 'original-native-read-preview-current.png') });
  await page.getByText('parity-workspace', { exact: true }).first().hover();
  await page.locator('[data-testid^="workspace-file-tree-button"]').click();
  await page.getByText('hello.txt', { exact: true }).first().dblclick();
  const tabs = page.locator('[data-side-pane-tab-id]');
  await tabs.filter({ hasText: 'hello.txt' }).waitFor();
  await page.getByText('Native parity file content', { exact: false }).first().waitFor();
  report.tabOrderBefore = await tabs.allTextContents();
  const a = await tabs.nth(0).boundingBox(), b = await tabs.nth(1).boundingBox();
  await drag(page, tabs.nth(0), b.x - a.x + 30, 0);
  report.tabOrderAfterDrag = await tabs.allTextContents();
  assert.notDeepEqual(report.tabOrderAfterDrag, report.tabOrderBefore);
  await tabs.filter({ hasText: 'README.md' }).click();
  report.postDragFirstClickActive = await tabs.filter({ hasText: 'README.md' }).getAttribute('data-state') === 'active';
  if (!report.postDragFirstClickActive) await tabs.filter({ hasText: 'README.md' }).click();
  await tabs.filter({ hasText: 'README.md' }).and(page.locator('[data-state="active"]')).waitFor();
  const width = (await page.locator('#browser').boundingBox()).width;
  await drag(page, page.locator('[data-workspace-side-pane-resize-handle]'), -75, 0);
  report.sidePaneWidth = { before: width, after: (await page.locator('#browser').boundingBox()).width };
  assert(report.sidePaneWidth.after > width + 30);
  await page.screenshot({ path: join(f.output, 'original-native-tabs-drag-current.png') });
  await tabs.filter({ hasText: 'hello.txt' }).click();
  await tabs.filter({ hasText: 'hello.txt' }).getByRole('button').click();
  assert.equal(await tabs.count(), 1);
  report.tabCloseRetainsReadme = await tabs.first().innerText();
  const sessionId = () => page.locator('[data-testid^="v4-session-pane"]').filter({ visible: true }).first().getAttribute('data-session-id');
  const first = await sessionId();
  await page.getByRole('button', { name: '返回任务', exact: true }).click();
  const firstRowTestId = await page.locator('[data-testid^="task-item-"]').first().getAttribute('data-testid');
  await page.getByText('新建任务', { exact: true }).first().click();
  await send('PARITY_RECOVER: second original session');
  await page.getByTestId('v4-timeline').getByText('PARITY_RECOVER_COMPLETE', { exact: true }).waitFor();
  const second = await sessionId();
  assert(first && second && first !== second);
  const beforeSwitch = model.requests.length;
  const rows = page.locator('[data-testid^="task-item-"]');
  report.sidebarRows = await rows.allTextContents();
  const secondRowTestId = await rows.evaluateAll((nodes, firstId) => nodes.find(n => n.getAttribute('data-testid') !== firstId)?.getAttribute('data-testid'), firstRowTestId);
  assert(secondRowTestId && secondRowTestId !== firstRowTestId);
  await page.getByTestId(firstRowTestId).click();
  await page.getByText('PARITY_READ_COMPLETE', { exact: true }).waitFor();
  assert.equal(await sessionId(), first);
  await page.getByTestId(secondRowTestId).click();
  await page.getByTestId('v4-timeline').getByText('PARITY_RECOVER_COMPLETE', { exact: true }).waitFor();
  assert.equal(await sessionId(), second);
  report.sessionSwitch = { first, second, noReplay: model.requests.length === beforeSwitch };
  assert(report.sessionSwitch.noReplay);
  await page.screenshot({ path: join(f.output, 'original-native-session-switch-current.png') });
  await page.getByTestId(secondRowTestId).click({ button: 'right' });
  const split = page.getByTestId('v4-task-open-in-split');
  report.conversationSplit = { entryVisible: await split.isVisible(), enabled: await split.isEnabled() };
  assert(report.conversationSplit.entryVisible && !report.conversationSplit.enabled);
  await page.screenshot({ path: join(f.output, 'original-native-split-unavailable-current.png') });
  await page.keyboard.press('Escape');
  assert.equal(report.pageErrors.length, 0);
}
